"""The India reference dataset (Section 6.2) — curated, looked up, consistent.

This is the self-maintained stand-in for Airopa's licensed India reference
dataset. It is keyed by sector, so two companies in the same sector always
receive the SAME India figures (the Section 6.2 consistency requirement), and
every value is a LOOKUP, never generated by a model inline (Design Principle,
Section 6.2).

The figures are v1 curated reference values drawn from public knowledge about
India's market, talent and policy landscape. They are deliberately coarse and
sector level. They DRIVE the India Market and Technology Hub scores; the raw
numbers are withheld from the public page (Section 9.1) and surface only in the
internal brief and the two week business case. Refine these against a licensed
dataset before volume use — each row carries its own as_of date for exactly that
reason.

Talent depth enum: shallow | moderate | deep | very_deep
"""
