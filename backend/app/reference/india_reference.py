@dataclass
class SectorReference:
    sector: str
    # India Market Opportunity inputs
    market_size_eur: int            # India market for the category
    market_growth: float            # annual
    downstream_growth: float
    segment_present: bool           # buying segment present in India at scale
    price_point_fit: str            # strong | moderate | weak
    adaptation: str                 # minimal | moderate | heavy
    peers_india_revenue: bool       # peers earn disclosed India revenue
    foreign_entrants_succeed: bool
    pli_scheme: bool                # sector named in a production linked incentive
    fdi_route: str                  # automatic | approval
    tariff_position: str            # favourable | neutral | adverse
    trade_agreement: str
    route_to_market: str            # established | partial | none
    approval_lead_months: int
    local_mfg_preference: bool
    china_plus_one: str             # strong | relevant | weak | n/a
    named_relocations: bool
    # Technology Hub inputs
    talent_depth: str
    talent_growth: float
    graduate_output: int            # relevant graduates per year, India
    salary_india_eur: int           # fully loaded, representative skill family
    salary_home_eur: int
    time_to_fill_india_wks: int
    time_to_fill_home_wks: int
    attrition: float
    sector_delivery_precedent: str  # strong | adjacent | weak | none
    top_cities: list               # candidate cities
    gcc_density: int                # GCC/SI density in the lead city
    # Peer penetration (share of European peers with an India centre)
    gcc_penetration: float
    penetration_recent_24m: int
    ip_intensity: str               # high | moderate | low (gates IP dimension)


